export const getShortsMetadata = (identifier) => {
  if (identifier === null || identifier === undefined) return null;
  const s = String(identifier).trim();
  if (!s) return null;

  // 1. Direct title match (case-insensitive)
  const lower = s.toLowerCase();
  for (const entry of Object.values(EDUCATION_SHORTS_CATALOG)) {
    if (entry && (entry.title?.trim().toLowerCase() === lower || entry.titleEn?.trim().toLowerCase() === lower)) {
      return entry;
    }
  }

  // 2. Intro check
  if (/intro/i.test(s)) {
    return EDUCATION_SHORTS_CATALOG[0];
  }

  // 3. Numeric / filename matching (e.g. "1", "1.mp4", "V1", "#01", "01/60", etc.)
  const m = s.match(/(?:^|#|v|\b)(\d+)\b/i);
  if (m) {
    const num = parseInt(m[1], 10);
    if (EDUCATION_SHORTS_CATALOG[num] !== undefined) {
      return EDUCATION_SHORTS_CATALOG[num];
    }
  }

  return null;
};
